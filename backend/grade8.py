def lesson(intro, theory, example, mistakes, checks, graph=None, second_example=None):
    content = {
        "intro": intro,
        "theory": list(theory),
        "examples": [{"prompt": example[0], "steps": list(example[1:])}],
        "mistakes": [{"error": error, "explanation": why} for error, why in mistakes],
        "checks": [{"prompt": prompt, "answer": str(answer)} for prompt, answer in checks],
    }
    if graph is not None:
        content["graph"] = graph
    if second_example is not None:
        content["examples"].append({"prompt": second_example[0], "steps": list(second_example[1:])})
    return content


def add(key, section, title, description, formula, material, *families, worked):
    topic_id = f"g8-{key}"
    material["examples"].append({"prompt": worked["ru"], "steps": worked["solution"]})
    TOPICS.append({
        "id": topic_id, "grade": 8, "section": section, "title": title,
        "description": description, "formula": formula, "lesson": material,
        "order": 10 + 2 * len(TOPICS),
        "sat": None,
    })
    FAMILIES[topic_id] = families


def expr(value):
    if isinstance(value, Fraction):
        return str(value)
    return str(value).replace("-", "−")


def signed(value):
    return f"+ {value}" if value >= 0 else f"− {-value}"


def problem(prompt, answer, guide, *steps, followup, verify=None, graph=None):
    output = {
        "ru": prompt, "en": prompt, "answer": float(answer) if isinstance(answer, Fraction) else answer,
        "hints": [guide, followup], "solution": [*steps, f"Ответ: {expr(answer)}."],
    }
    if verify is not None:
        output["verify"] = float(verify) if isinstance(verify, Fraction) else verify
    if graph is not None:
        output["graph"] = graph
    return output


def root_bound(i, j):
    n = 11 + i
    k = n*n + 1 + j
    return problem(
        f"Чему равна целая часть числа √{k}?",
        n, "Сравни подкоренное число с квадратами соседних целых.",
        f"{n}² = {n*n} < {k} < {(n+1)**2} = {n+1}².",
        f"На неотрицательной полуоси квадрат возрастает, поэтому {n} < √{k} < {n+1}.",
        verify=isqrt(k),

        followup="Найди целое n с n²≤a<(n+1)² для подкоренного a. Тогда целая часть корня равна n.")


