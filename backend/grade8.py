def discriminant_root(i, j):
    r, s = i+2, j+13
    b, c = -(r+s), r*s
    return problem(
        f"Найдите больший корень уравнения x² {signed(b)}x + {c} = 0.",
        s, "Найди дискриминант b²−4ac, затем проверь знак перед корнем.",
        f"D = ({b})² − 4·{c} = {(r-s)**2}.",
        f"x₁ = ({-b}−{s-r})/2 = {r}, x₂ = ({-b}+{s-r})/2 = {s}.",
        verify=max(x for x in range(0, s+1) if x*x+b*x+c==0),

        followup="В формуле x=(−b±√D)/(2a) знак перед √D определяет два корня. Выбери требуемый и проверь подстановкой.")


