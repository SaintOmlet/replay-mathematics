def extract_radical(i, j):
    a, m = i+2, SQUAREFREE[j]
    return problem(
        f"Упростите √{a*a*m} до вида k√{m}. Чему равно k?",
        a, "Найди множитель под корнем, который является полным квадратом.",
        f"{a*a*m} = {a*a} · {m}, оба множителя неотрицательны.",
        f"Свойство произведения корней даёт √{a*a} · √{m} = {a}√{m}.",
        verify=isqrt((a*a*m)//m),

        followup="Найденный квадрат можно вынести из-под корня его положительным корнем. Оставшийся множитель сохраняется под корнем.")


