def root_inverse(i, j):
    shift, level = i-4, j+2
    ans = level*level+shift
    return problem(
        f"График y = √(x {signed(-shift)}) пересекает горизонтальную прямую y = {level}. Найдите абсциссу пересечения.",
        ans, "Ищи одно значение x, при котором высоты графиков равны.",
        f"Так как {level} ≥ 0, квадрат равенства √(x {signed(-shift)}) = {level} равносилен исходному равенству на его области определения.",
        f"x {signed(-shift)} = {level*level}, значит x = {level*level} {signed(shift)}.",
        f"Проверка: под корнем {ans-shift}, поэтому высота равна {level}.",
        verify=next(k for k in range(shift, ans+1) if sqrt(k-shift)==level),

        followup="Возведи равенство корня заданной высоте в квадрат, затем проверь неотрицательность обеих частей.")


