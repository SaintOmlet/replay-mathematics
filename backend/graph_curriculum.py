def key(values):
    return json.dumps(values, sort_keys=True, separators=(",", ":"))


def graph_spec(model, *, points=(), reference=None, view=None):
    definitions = {
        "line": (("m", "Наклон m", -6, 6, .5, 0), ("b", "Пересечение с Oy, b", -15, 15, .5, -8)),
        "parabola": (("a", "Коэффициент a", -6, 6, .5, 1), ("h", "Абсцисса вершины h", -10, 10, .5, 0),
                     ("k", "Ордината вершины k", -15, 15, .5, -8)),
    }
    spec = {
        "kind": "graph", "model": model,
        "parameters": [dict(zip(("key", "label", "min", "max", "step", "initial"), row)) for row in definitions[model]],
        "view": view or {"xmin": -10, "xmax": 10, "ymin": -30, "ymax": 30},
    }
    if points:
        spec["points"] = list(points)
    if reference:
        spec["reference"] = reference
    return spec


def point(x, y, label):
    return {"x": x, "y": y, "label": label}


def task(prompt, values, response, hints, solution, diagnostics=()):
    bounds = {item["key"]: item for item in response["parameters"]}
    return {
        "ru": prompt, "en": prompt, "answer": key(values), "response": response,
        "hints": list(hints), "solution": list(solution),
        "diagnostics": [{"answer": key(wrong), "explanation": explanation}
                        for wrong, explanation in diagnostics if wrong != values
                        and all(bounds[name]["min"] <= value <= bounds[name]["max"] for name, value in wrong.items())],
    }


