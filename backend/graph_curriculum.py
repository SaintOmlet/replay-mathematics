def line_two_points(i, j):
    m, b = (i-5)/2, j-4
    y1, y2 = b-2*m, b+2*m
    return task(
        f"Построй прямую через A(−2;{y1:g}) и B(2;{y2:g}). Должны выполняться оба условия одновременно.",
        {"m": m, "b": b}, graph_spec("line", points=(point(-2, y1, "A"), point(2, y2, "B"))),
        ("Наклон — отношение изменения y к изменению x между двумя заданными точками.",
         "После нахождения наклона подставь координаты одной точки в y=mx+b и вырази свободный член."),
        (f"Изменение абсциссы равно 2−(−2)=4, изменение ординаты {y2:g}−({y1:g})={4*m:g}.",
         f"Поэтому m=({4*m:g})/4={m:g}.",
         f"Подстановка точки A даёт b={y1:g}−({m:g})·(−2)={b}. Проверка точки B даёт {y2:g}."),
        (({"m": -m, "b": b}, "Вычитай координаты точек в одном порядке и в числителе, и в знаменателе наклона."),))


