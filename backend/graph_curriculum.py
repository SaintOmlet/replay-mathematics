def parabola_vertex(i, j):
    h, k, a = i-5, j-4, 1 if i % 2 == 0 else -1
    direction = "вверх" if a > 0 else "вниз"
    return task(
        f"Построй параболу с вершиной V({h};{k}), ветвями {direction} и коэффициентом |a|=1. Используй вид y=a(x−h)²+k.",
        {"a": a, "h": h, "k": k}, graph_spec("parabola", points=(point(h, k, "V"),)),
        ("В записи y=a(x−h)²+k координаты вершины — h и k.",
         "Проверь знак a по направлению ветвей, затем проверь вершину подстановкой x=h."),
        (f"Вершина задаёт h={h} и k={k}.", f"Ветви направлены {direction}, поэтому при |a|=1 получаем a={a}.",
         f"При x={h} квадрат равен нулю и y={k}. При отклонении x на 1 изменение y равно {a}."),
        (({"a": a, "h": -h, "k": k}, "Знак горизонтального сдвига перепутан. Внутри скобок стоит x−h, а абсцисса вершины равна h."),
         ({"a": -a, "h": h, "k": k}, "Вершина выбрана верно, но направление ветвей противоположное. Его определяет знак a.")))


def parabola_through_point(i, j):
    h, k = i-5, j-4
    a = (j % 5+1) * (1 if j < 5 else -1)
    px, py = h+2, k+4*a
    return task(
        f"Построй параболу с вершиной V({h};{k}), проходящую через P({px};{py}). Найди все параметры y=a(x−h)²+k.",
        {"a": a, "h": h, "k": k}, graph_spec("parabola", points=(point(h, k, "V"), point(px, py, "P"))),
        ("Координаты вершины сразу определяют h и k. Для определения a используй вторую точку.",
         "Вычти k из ординаты точки P и раздели результат на квадрат разности x_P−h."),
        (f"Из вершины получаем h={h}, k={k}.", f"Точка P даёт {py}=a·({px}−({h}))²+({k})=4a+({k}).",
         f"Следовательно, a=({py}−({k}))/4={a}. Коэффициент отличен от нуля, полученная функция является квадратичной."),
        (({"a": 2*a, "h": h, "k": k}, "Проверь знаменатель при определении a. Разность абсцисс нужно возвести в квадрат."),))


def parabola_transformation(i, j):
    h, k, a = i-5, j-4, 2 if i % 2 == 0 else -2
    horizontal = f"вправо на {h}" if h >= 0 else f"влево на {-h}"
    vertical = f"вверх на {k}" if k >= 0 else f"вниз на {-k}"
    reflected = "отразили относительно оси Ox и " if a < 0 else ""
    return task(
        f"Ординаты графика y=x² умножили на 2, затем {reflected}перенесли график {horizontal} и {vertical}. Построй полученную параболу.",
        {"a": a, "h": h, "k": k}, graph_spec("parabola",
            reference={"model": "parabola", "parameters": {"a": 1, "h": 0, "k": 0}}),
        ("Отдельно определи растяжение и отражение по вертикали, затем положение новой вершины.",
         "Умножение ординат на 2 меняет |a|. Отражение относительно Ox меняет знак a. Горизонтальный перенос входит в x−h."),
        (f"Вертикальное растяжение даёт |a|=2; с учётом отражения a={a}.",
         f"Вершина (0;0) после переносов находится в ({h};{k}), поэтому h={h}, k={k}.",
         f"Искомая функция y=({a})(x−({h}))²+({k}). Сдвиг применяется после вертикального преобразования."),
        (({"a": a, "h": -h, "k": k}, "Направление горизонтального переноса перепутано. Перенос вправо на h записывается как x−h."),
         ({"a": a/2, "h": h, "k": k}, "Направление и вершина сохранены, но вертикальное растяжение потеряно. Ординаты относительно вершины должны удвоиться.")))


