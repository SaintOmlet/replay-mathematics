    k=(i+2)*(j+1)
    case=i%4
    polynomials=(f"{a+k}x²+{b}x+{a+b}={k}x²",f"{a+k}x²−{b}x={k}x²",
                 f"{a+k}x²−{b*b}={k}x²",f"{k}x²+{a}x+{b}={k}x²")
    reduced=(f"{a}x²+{b}x+{a+b}=0",f"{a}x²−{b}x=0",f"{a}x²−{b*b}=0",f"{a}x+{b}=0")
    labels=("Полное квадратное","Неполное квадратное, c=0","Неполное квадратное, b=0","Линейное, не квадратное")
    return choice("Классифицируйте уравнение "+polynomials[case]+" после приведения к стандартному виду.",labels,case,i,j,
        ("Приведи к ax²+bx+c=0 и проверь a≠0.","После определения степени выясни, какие из b и c равны нулю."),
        ("После переноса правой части получаем "+reduced[case]+".","Здесь подходит описание: "+labels[case]+"."))


