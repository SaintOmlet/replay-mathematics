def n(value):
    return str(Q(value))


def task(prompt, answer, hints, steps, response=None):
    if isinstance(answer,Q):
        answer=answer.numerator if answer.denominator==1 else float(answer)
    value={"ru":prompt,"en":prompt,"answer":answer,"hints":list(hints),"solution":list(steps)}
    if response:
        value["response"]=response
    return value


def pair(prompt,a,b,hints,steps,parts=("Первая величина","Вторая величина")):
    return task(prompt,n(a)+";"+n(b),hints,steps,{"kind":"pair","parts":list(parts)})


def choice(prompt,labels,index,i,j,hints,steps):
    shift=(i+3*j)%len(labels)
    order=list(range(len(labels)))
    order=order[shift:]+order[:shift]
    options=[{"value":chr(97+k),"label":labels[v]} for k,v in enumerate(order)]
    return task(prompt,chr(97+order.index(index)),hints,steps,{"kind":"choice","options":options})


def sequence(prompt,steps,i,j,hints,solution):
    order=list(range(len(steps)))
    shift=(i+j)%len(order)
    order=order[shift:]+order[:shift]
    if i%2:
        order.reverse()
    options=[{"value":chr(97+k),"label":steps[v]} for k,v in enumerate(order)]
    answer=",".join(chr(97+order.index(v)) for v in range(len(order)))
    return task(prompt,answer,hints,solution,{"kind":"sequence","options":options})


def expression(prompt,answer,hints,steps,form="expanded",variables=("x",)):
    return task(prompt,answer,hints,steps,{"kind":"expression","variables":list(variables),"form":form})


