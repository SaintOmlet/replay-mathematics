def modulus_substitution(i, j):
    h, a = i - 5, j + 1
    b = a + i + 2
    case = i % 5
    t_roots = ((-a, -b), (0, -a), (a, -b), (a, b), (0, a))[case]
    coefficient, constant = -sum(t_roots), t_roots[0] * t_roots[1]
    admissible = sorted({root for root in t_roots if root >= 0})
    roots = {h + sign * root for root in admissible for sign in (-1, 1)}
    answer = format_roots(roots)
    return task(
        f"Решите уравнение (x−({h}))²+({coefficient})·|x−({h})|+({constant})=0. Укажите все действительные корни.",
        answer,
        ("Обозначь t=|x−h|. При этой замене t≥0, а (x−h)²=t².",
         "Найди оба корня квадратного уравнения по t и сначала отбрось отрицательные. Для t=0 получится один x, для t>0 — два."),
        (f"Замена t=|x−({h})|≥0 приводит к t²+({coefficient})t+({constant})=0.",
         f"Разложение (t−({t_roots[0]}))(t−({t_roots[1]}))=0 даёт t={t_roots[0]} или t={t_roots[1]}.",
         "Допустимые t: " + ("; ".join(map(str, admissible)) if admissible else "отсутствуют, так как оба отрицательны") + ".",
         f"Возвращаемся к x={h}±t и оставляем каждый различный корень один раз. Ответ {answer}."), "roots")


def absolute_quadratic(i, j):
    h, a, b = i - 4, j + 1, i + j + 3
    case = j % 4
    inside, outside = ((a*a, -b), (-a*a, a*a), (-a*a, a*a+b*b),
                       (Fraction(a*a+b*b, 2), Fraction(b*b-a*a, 2)))[case]
    candidates = (inside + outside, inside - outside) if outside >= 0 else ()
    values = set()
    for squared in candidates:
        if squared < 0:
            continue
        # Each nonnegative radicand in this authored grid is a perfect square.
        root = next(n for n in range(0, 40) if n*n == squared)
        values.update((h-root, h+root))
    answer = format_roots(values)
    return task(
        f"Решите |(x−({h}))²−({number(inside)})|={number(outside)}. Укажите все действительные корни.",
        answer,
        ("Сначала проверь знак правой части: модуль не может равняться отрицательному числу.",
         "При неотрицательной правой части рассмотри оба равенства для выражения внутри модуля. У квадратов оставь только неотрицательные правые части."),
        (f"Правая часть равна {number(outside)}. " + ("Она отрицательна, поэтому решений нет." if outside < 0 else "Она неотрицательна, раскрываем модуль двумя равенствами."),
         "После переноса получаем значения (x−h)²: " + ("; ".join(number(v) for v in candidates) if candidates else "допустимых значений нет") + ".",
         "Отрицательный квадрат невозможен. Из положительного квадрата получаем два корня, из нулевого — один.",
         f"Объединяем корни обеих ветвей без повторов. Ответ {answer}."), "roots")


