def quadratic_set(a, b, comparison, coefficient=1):
    closed = comparison in ("≤", "≥")
    wants_positive = comparison in (">", "≥")
    outside = wants_positive == (coefficient > 0)
    if a == b:
        if outside:
            return ((-float("inf"), float("inf"), False, False),) if closed else (
                (-float("inf"), a, False, False), (a, float("inf"), False, False))
        return ((a, a, True, True),) if closed else ()
    return ((-float("inf"), a, False, closed), (b, float("inf"), closed, False)) if outside else ((a, b, closed, closed),)


