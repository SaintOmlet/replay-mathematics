"""Additional goal-aligned school material and structured-answer exercises.

Construction and proof chains check knowledge of a method, not a freehand or
compass construction. GOAL_EVIDENCE therefore never labels these goals full.
All tasks are original and deterministic in the 10 by 10 parameter grid.
"""

from fractions import Fraction
from math import gcd

TOPICS = []
FAMILIES = {}
LEVELS_BY_TOPIC = {}
LEGACY_LESSONS = {}
GOAL_EVIDENCE = []


def value(number):
    if isinstance(number, Fraction):
        return str(number.numerator) if number.denominator == 1 else f"{number.numerator}/{number.denominator}"
    return str(number).replace("+-", "−")


def exercise(prompt, answer, hint, *solution, response=None, graph=None):
    if isinstance(answer, Fraction):
        answer = answer.numerator if answer.denominator == 1 else float(answer)
    result = {
        "ru": prompt, "en": prompt, "answer": answer,
        "hints": [hint, "Сверь выбранные действия с определением или теоремой урока. Сначала выполни обоснование, затем вычисление."],
        "solution": list(solution),
    }
    if response:
        result["response"] = response
    if graph:
        result["graph"] = graph
    return result


def pair(prompt, x, y, hint, *steps, parts=("Первая величина", "Вторая величина"), graph=None):
    return exercise(prompt, f"{value(x)};{value(y)}", hint, *steps,
                    response={"kind": "pair", "parts": list(parts)}, graph=graph)


def choose(prompt, labels, correct, hint, *steps, shift=0):
    """Rotate option positions independently of the mathematical answer."""
    positions = list(range(len(labels)))
    positions = positions[shift % len(labels):] + positions[:shift % len(labels)]
    options = [{"value": chr(97 + k), "label": labels[index]} for k, index in enumerate(positions)]
    key = chr(97 + positions.index(correct))
    return exercise(prompt, key, hint, *steps, response={"kind": "choice", "options": options})


def chain(prompt, ordered, hint, *steps, shift=0):
    positions = list(range(len(ordered)))
    positions = positions[shift % len(ordered):] + positions[:shift % len(ordered)]
    if shift % 2:
        positions.reverse()
    options = [{"value": chr(97 + k), "label": ordered[index]} for k, index in enumerate(positions)]
    key = ",".join(chr(97 + positions.index(index)) for index in range(len(ordered)))
    return exercise(prompt, key, hint, *steps, response={"kind": "sequence", "options": options})


def material(intro, theory, examples, mistakes, checks):
    return {
        "intro": intro, "theory": list(theory),
        "examples": [{"prompt": prompt, "steps": list(steps)} for prompt, *steps in examples],
        "mistakes": [{"error": error, "explanation": explanation} for error, explanation in mistakes],
        "checks": [{"prompt": prompt, "answer": answer} for prompt, answer in checks],
    }


def add(key, grade, section, title, formula, lesson, families, levels=("easy", "medium", "hard"), goals=()):
    TOPICS.append({
        "id": key, "grade": grade, "section": section, "title": title,
        "description": lesson["intro"], "formula": formula, "lesson": lesson,
        "order": 180 + len(TOPICS), "sat": "", "satReady": False,
    })
    FAMILIES[key] = tuple(families)
    LEVELS_BY_TOPIC[key] = tuple(levels)
    for subject, code, status, evidence in goals:
        GOAL_EVIDENCE.append({
            "subject": subject, "code": code, "topic": key, "status": status, "evidence": evidence,
        })


