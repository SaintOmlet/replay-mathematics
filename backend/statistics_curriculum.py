def full_table(i,j):
    x=[i+1,i+2,i+4]
    f=[j+2,(i+j)%8+2,i+3]
    sample=[x[k] for k in range(3) for _ in range(f[k])]
    sample=sample[::2]+sample[1::2][::-1]
    return task("Составьте полную таблицу абсолютных частот выборки: "+", ".join(map(str,sample))+". Заполните частоту каждого указанного значения.",
                list(map(str,x)),f,"frequency_table",
                ("Каждое различное значение образует одну строку.","Сосчитай все повторы; сумма частот должна совпасть с объёмом выборки."),
                ("Варианты в возрастающем порядке: "+", ".join(map(str,x))+".",
                 "Абсолютные частоты соответственно "+", ".join(map(str,f))+f"; их сумма {sum(f)} равна объёму выборки."))


def polygon_absolute(i,j):
    x=[i+1,i+3,i+6,i+8]
    f=[j+2,i+2,j+5,(i+j)%9+1]
    return task("Постройте полигон абсолютных частот. Таблица (значение: частота): "+"; ".join(f"{a}: {b}" for a,b in zip(x,f))+". Задайте высоту точки над каждым значением.",
                list(map(str,x)),f,"frequency_polygon",
                ("Абсциссы — значения признака, ординаты — их абсолютные частоты.","Вершины соединяются по возрастанию значений; расстояния между значениями здесь различаются."),
                ("Нужные вершины: "+"; ".join(f"({a};{b})" for a,b in zip(x,f))+".",
                 "Соединяем соседние вершины в порядке возрастания абсцисс. Высоты равны частотам, а не накопленным суммам."),x=x)


def polygon_from_sample(i,j):
    x=[i+2,i+4,i+5]
    f=[j+1,i+2,(i+j)%7+3]
    sample=[x[k] for k in (2,0,1) for _ in range(f[k])]
    return task("По выборке "+", ".join(map(str,sample))+" постройте полигон абсолютных частот. Сначала сосчитайте повторы и задайте все ординаты.",
                list(map(str,x)),f,"frequency_polygon",
                ("Сначала сгруппируй равные наблюдения.","Над каждым значением поставь точку на высоте количества его появлений."),
                ("Частоты в порядке возрастания значений: "+", ".join(map(str,f))+".",
                 "Вершины полигона: "+"; ".join(f"({a};{b})" for a,b in zip(x,f))+"."),x=x)


def histogram(i,j):
    left=i-3
    widths=[j%3+1,2+j%4,1+(i+j)%4]
    if len(set(widths))==1:
        # Every prompt explicitly asks for unequal-width intervals.
        widths[-1]+=1
    bounds=[left]
    for width in widths: bounds.append(bounds[-1]+width)
    counts=[i+3,j+4,i+j+5]
    heights=[Fraction(f,w) for f,w in zip(counts,widths)]
    labels=[f"[{bounds[k]};{bounds[k+1]}"+("]" if k==2 else ")") for k in range(3)]
    return task("Постройте гистограмму абсолютных частот для интервалов разной ширины. Интервал: количество наблюдений — "+
                "; ".join(f"{label}: {f}" for label,f in zip(labels,counts))+". Площадь каждого столбца должна равняться его частоте. Введите все высоты (плотности); дроби допустимы.",
                labels,heights,"histogram",
                ("Сначала вычисли длину каждого интервала.","Площадь столбца равна ширина × высота. Поэтому высота = частота / ширина."),
                ("Ширины интервалов: "+", ".join(map(str,widths))+".",
                 "Высоты: "+", ".join(f"{f}/{w}={h}" for f,w,h in zip(counts,widths,heights))+". Умножение каждой высоты на её ширину возвращает исходную частоту."),bins=bounds)


