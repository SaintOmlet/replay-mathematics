def val(value):
    return str(Q(value))


def exercise(prompt, answer, hints, *steps, response=None):
    if isinstance(answer, Q):
        answer = answer.numerator if answer.denominator == 1 else float(answer)
    result = {"ru": prompt, "en": prompt, "answer": answer,
              "hints": list(hints), "solution": list(steps)}
    if response:
        result["response"] = response
    return result


def pair(prompt, first, second, hints, *steps):
    return exercise(prompt, f"{val(first)};{val(second)}", hints, *steps,
                    response={"kind": "pair", "parts": ["Первая величина", "Вторая величина"]})


def expression(prompt, answer, hints, *steps, variable="x"):
    return exercise(prompt, answer, hints, *steps,
                    response={"kind": "expression", "variables": [variable], "form": "expanded"})


def choose(prompt, labels, correct, hint, *steps, shift=0, followup):
    positions = list(range(len(labels)))
    positions = positions[shift % len(labels):] + positions[:shift % len(labels)]
    options = [{"value": chr(97 + k), "label": labels[index]} for k, index in enumerate(positions)]
    key = chr(97 + positions.index(correct))
    return exercise(prompt, key, (hint, followup), *steps,
                    response={"kind": "choice", "options": options})


def chain(prompt, ordered, hint, *steps, shift=0, followup):
    positions = list(range(len(ordered)))
    positions = positions[shift % len(ordered):] + positions[:shift % len(ordered)]
    if shift % 2:
        positions.reverse()
    options = [{"value": chr(97 + k), "label": ordered[index]} for k, index in enumerate(positions)]
    key = ",".join(chr(97 + positions.index(index)) for index in range(len(ordered)))
    return exercise(prompt, key, (hint, followup), *steps,
                    response={"kind": "sequence", "options": options})


