def trig_period_parity(i, j):
    c,k=i+1,j+1
    name=("sin","cos","tan","cot")[(i+j)%4]
    even=name=="cos"
    numerator=2 if name in ("sin","cos") else 1
    period=f"{numerator}π/{k}"
    parity="чётная" if even else "нечётная"
    opposite="нечётная" if even else "чётная"
    return choose(f"Для y={c}·{name}({k}x) выберите наименьший положительный период и чётность.",
                  [f"T={period}; {parity}", f"T={2*numerator}π/{k}; {parity}",
                   f"T={period}; {opposite}", f"T={numerator}π/({2*k}); {parity}"],0,
                  "Множитель внутри аргумента делит основной период; внешний ненулевой множитель его не меняет.",
                  f"Базовый период {numerator}π, поэтому новый {period}.",
                  f"Подстановка −x показывает: функция {parity}.",shift=i+j, followup='Отдельно подставь x+T и −x: периодичность и чётность — разные свойства.')


