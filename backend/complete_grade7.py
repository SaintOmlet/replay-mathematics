def n(value):
    return str(Fraction(value))


def polynomial_text(*coefficients):
    """Full standard polynomial, with zero coefficients genuinely removed."""
    terms = []
    for degree, coefficient in zip(range(len(coefficients)-1,-1,-1), coefficients):
        if coefficient:
            terms.append(f"{n(coefficient)}*x^{degree}" if degree else n(coefficient))
    return "+".join(terms).replace("+-", "-") or "0"


def task(prompt, answer, hint1, hint2, *steps, response=None):
    if isinstance(answer, Fraction):
        answer = float(answer)
    result = {"ru": prompt, "en": prompt, "answer": answer,
              "hints": [hint1, hint2], "solution": list(steps)}
    if response:
        result["response"] = response
    return result


def expression(prompt, answer, hint1, hint2, *steps, form="expanded", variables=("x",)):
    return task(prompt, answer, hint1, hint2, *steps,
                response={"kind": "expression", "variables": list(variables), "form": form})


def pair(prompt, a, b, hint1, hint2, *steps, parts=("Первая величина", "Вторая величина")):
    return task(prompt, f"{n(a)};{n(b)}", hint1, hint2, *steps,
                response={"kind": "pair", "parts": list(parts)})


def selection(prompt, labels, correct, hint1, hint2, *steps, shift=0):
    result = choose(prompt, labels, correct, hint1, *steps, shift=shift)
    result["hints"][1] = hint2
    return result


