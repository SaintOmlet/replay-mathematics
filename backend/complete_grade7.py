def scientific_compare(i,j):
    a = Fraction(i+11,10) * (-1 if i%3==0 else 1)
    b = Fraction(j+11,10) * (-1 if j%3==0 else 1)
    exponent = i-j
    difference = (i+j)%3-1
    a_value = a*Fraction(10)**exponent
    b_value = b*Fraction(10)**(exponent+difference)
    relation = 0 if a_value<b_value else 1 if a_value==b_value else 2
    aligned = b*Fraction(10)**difference
    return selection(f"Сравните A=({n(a)})·10^{exponent} и B=({n(b)})·10^{exponent+difference}.",
                     ("A<B","A=B","A>B"),relation,
                     "Для сравнения приведи обе записи к одинаковой степени десяти.",
                     "После выравнивания порядков сравни коэффициенты с учётом их знаков.",
                     f"При общем положительном множителе 10^{exponent} сравниваем {n(a)} и {n(aligned)}.",
                     f"Получаем {('A<B','A=B','A>B')[relation]}; множитель степени десяти положителен.",shift=i+2*j)


