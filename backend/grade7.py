def exercise(prompt, answer, hint, *steps, followup, graph=None):
    if isinstance(answer, Fraction):
        answer = int(answer) if answer.denominator == 1 else float(answer)
    result = dict(ru=prompt, en=prompt, answer=answer, hints=[hint, followup], solution=list(steps))
    if graph is not None:
        result["graph"] = graph
    return result


def lesson(intro, theory, examples, mistakes, checks, graph=None):
    result = dict(
        intro=intro, theory=list(theory),
        examples=[dict(prompt=prompt, steps=list(steps)) for prompt, *steps in examples],
        mistakes=[dict(error=wrong, explanation=why) for wrong, why in mistakes],
        checks=[dict(prompt=prompt, answer=answer) for prompt, answer in checks],
    )
    if graph is not None:
        result["graph"] = graph
    return result


def topic(key, section, title, description, formula, study):
    return dict(id="g7-" + key, grade=GRADE, section=section, title=title,
                description=description, formula=formula, lesson=study,
                sat="", icon="")


