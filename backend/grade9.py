def exercise(prompt, answer, hint, *steps, followup, verify=None, graph=None):
    if isinstance(answer, Fraction):
        answer = answer.numerator if answer.denominator == 1 else float(answer)
    result = {
        "ru": prompt,
        "en": prompt,
        "answer": answer,
        "hints": [hint, followup],
        "solution": list(steps),
    }
    if verify is not None:
        result["verify"] = float(verify) if isinstance(verify, Fraction) else verify
    if graph is not None:
        result["graph"] = graph
    return result


def lesson(intro, theory, example, steps, mistakes, checks, graph=None):
    result = {
        "intro": intro,
        "theory": list(theory),
        "examples": [{"prompt": example, "steps": list(steps)}],
        "mistakes": [{"error": error, "explanation": explanation} for error, explanation in mistakes],
        "checks": [{"prompt": prompt, "answer": answer} for prompt, answer in checks],
    }
    if graph is not None:
        result["graph"] = graph
    return result


