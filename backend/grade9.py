def point_gap(i, j):
    x, y = i+1, i+2*j+5
    bound = 2*x+j+3
    distance = j+1
    return exercise(f"Для области x+y≤{bound} точка A({x}; {y}) лежит снаружи. "
                    "На сколько нужно уменьшить её ординату при неизменном x, чтобы попасть ровно на границу?",
                    distance, "Подставь абсциссу точки в уравнение границы.",
                    f"При x={x} на границе y={bound}−{x}={y-distance}.",
                    f"Разность ординат {y}−{y-distance}={distance}.", verify=x+y-bound,
                    followup="Вычти допустимую ординату границы из текущей ординаты точки. Эта положительная разность показывает, насколько точку нужно опустить.")


def count_under_line(i, j):
    m, b = i+3, j+2
    bound = m+b
    valid = (m+1)*(bound+1)-m*(m+1)//2
    return exercise(f"Сколько точек с целыми координатами удовлетворяют 0≤x≤{m}, y≥0 и x+y≤{bound}?",
                    valid, "Сосчитай возможные y при каждом целом x.",
                    f"Для фиксированного x целые ординаты от 0 до {bound}−x, всего {bound+1}−x штук.",
                    f"Складываем {m+1} чисел от {bound+1} до {b+1}: сумма {valid}.",
                    verify=sum(1 for x in range(m+1) for y in range(bound+1) if x+y<=bound),
                    followup="Для каждого x выпиши наибольшее допустимое целое y. Суммируй число целых от нижней границы до него.")


def count_exclusion(i, j):
    p, q = i+3, j+4
    # Strictly below/on the diagonal is counted using symmetry about the rectangle centre.
    diagonal = gcd(p,q)+1
    below = ((p+1)*(q+1)-diagonal)//2
    usable = below-p
    return exercise(f"В прямоугольнике 0≤x≤{p}, 0≤y≤{q} считайте только узлы с целыми координатами, "
                    f"которые лежат строго ниже диагонали y={q}x/{p} и выше оси Ox. Сколько узлов подходит?",
                    usable, "Отражение относительно центра прямоугольника меняет местами верх и низ диагонали.",
                    f"На диагонали находится НОД({p}; {q})+1={diagonal} целых узлов: шаг по x равен {p//gcd(p,q)}.",
                    f"Остальные делятся поровну между полуплоскостями. Ниже диагонали {below} узлов.",
                    f"Убираем {p} узлов на оси Ox при x от 1 до {p}; остаётся {usable}.",
                    verify=sum(1 for x in range(p+1) for y in range(1,q+1) if p*y<q*x),
                    followup="Отдельно посчитай точки на диагонали. Остальные точки делятся на две равные группы по разные стороны.")


